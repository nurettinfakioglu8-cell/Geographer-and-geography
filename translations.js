// Ülke/dağ/başkent/kıta vb. isimlerin dile göre çevirileri.
// Türkçe için ayrı bir çeviriye gerek yok: orijinal veriler zaten Türkçe
// (data.js içindeki COUNTRY_NAMES, MOUNTAINS[].name, CONTINENT_NAMES vb.)
let COUNTRY_NAMES_I18N   = {};
let PHYSICAL_NAMES_I18N  = {};
let PHYSICAL_TYPE_I18N   = {};
let MOUNTAIN_COUNTRY_I18N = {};
let CONTINENT_I18N       = {};
let CAPITAL_I18N         = {};
let PHYSICAL_I18N        = {};

const _loadedLangs = new Set(['tr']);
const _langLoadPromises = {};

// name-first sözlük parçasını (örn. physical_names) global objeye yedirir:
// TARGET[trName][lang] = value  — app.js'teki mevcut okuma şekli değişmeden çalışır.
function _mergeNameFirst(target, pack, lang) {
  for (const trName in pack) {
    if (!target[trName]) target[trName] = {};
    target[trName][lang] = pack[trName];
  }
}

/**
 * Verilen dili (lang) asenkron olarak yükler. Zaten yüklenmişse hemen döner.
 * Ağ hatası durumunda hatayı fırlatır (çağıran taraf yakalayıp kullanıcıya
 * bilgi vermeli — bkz. app.js selectLang()).
 */
function loadLanguagePack(lang) {
  if (lang === 'tr' || _loadedLangs.has(lang)) return Promise.resolve(true);
  if (_langLoadPromises[lang]) return _langLoadPromises[lang];

  _langLoadPromises[lang] = fetch('translations/' + lang + '.json')
    .then(res => {
      if (!res.ok) throw new Error('HTTP ' + res.status);
      return res.json();
    })
    .then(pack => {
      TRANSLATIONS[lang] = pack.strings || {};
      COUNTRY_NAMES_I18N[lang] = pack.country_names || {};
      _mergeNameFirst(PHYSICAL_NAMES_I18N, pack.physical_names || {}, lang);
      _mergeNameFirst(PHYSICAL_TYPE_I18N, pack.physical_type || {}, lang);
      _mergeNameFirst(MOUNTAIN_COUNTRY_I18N, pack.mountain_country || {}, lang);
      _mergeNameFirst(CONTINENT_I18N, pack.continent || {}, lang);
      _mergeNameFirst(CAPITAL_I18N, pack.capital || {}, lang);
      _mergeNameFirst(PHYSICAL_I18N, pack.physical_desc || {}, lang);
      _loadedLangs.add(lang);
      return true;
    })
    .catch(err => {
      delete _langLoadPromises[lang];
      console.error('Dil paketi yüklenemedi (' + lang + '):', err);
      throw err;
    });
  return _langLoadPromises[lang];
}
